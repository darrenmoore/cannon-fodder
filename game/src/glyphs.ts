/**
 * The chrome typeface, as data.
 *
 * One table, two renderers, and that is the whole point of it living here.
 * `render/chromefont.ts` plots these rows straight onto a canvas; 
 * `ui/pixelface.ts` emits them as a TrueType file the DOM installs as an
 * `@font-face`. Both halves of the game therefore draw the *same letterforms*,
 * which is what 004 H3 was actually asking for -- the complaint was never that
 * the chrome font was ugly, it was that the DOM used whatever monospace the
 * player happened to have, so the game looked different on every machine and
 * disagreed with its own canvas on the same one.
 *
 * It sits at the top level next to `config.ts` and `types.ts` rather than
 * inside either `render/` or `ui/`, because it belongs to neither and nothing
 * in `ui/` imports from `render/`. Keeping that true is cheaper than the one
 * import it would take to break it.
 *
 * Five wide, seven tall, one column of side bearing. Uppercase only by design:
 * the reference chrome has no lowercase anywhere, and folding the lowercase
 * codepoints onto their capitals means existing mixed-case strings come out in
 * caps without every label in the game being rewritten.
 */

